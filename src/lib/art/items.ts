const EMPTY = "................";

/** `start`번 줄부터 `rows`를 놓고 나머지는 빈 줄 */
function layer(start: number, rows: string[]): string[] {
  return Array.from({ length: 16 }, (_, y) => rows[y - start] ?? EMPTY);
}

